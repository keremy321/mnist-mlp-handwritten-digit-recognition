"""Segment a photographed handwritten number and evaluate a trained MNIST MLP.

Uses the existing model.py and the checkpoint generated by train.py.
No training or test-set-based tuning is performed here.

Example:
    python predict_handwriting.py --image handwriting/student_number.jpg \
        --rotate 90 --number 23120205035 \
        --model results/lower_lr/best_model.pt
"""

import argparse
import csv
import json
from pathlib import Path

import cv2
import numpy as np
from PIL import Image, ImageDraw, ImageFont


def parse_args():
    parser = argparse.ArgumentParser(description="Predict handwritten digits using your trained MNIST MLP")
    parser.add_argument("--image", type=Path, required=True, help="Original photo of handwritten digits")
    parser.add_argument("--model", type=Path, default=Path("results/lower_lr/best_model.pt"))
    parser.add_argument("--number", type=str, default=None, help="Correct digit sequence; used ONLY for evaluation")
    parser.add_argument("--output-dir", type=Path, default=Path("results/handwriting"))
    parser.add_argument("--rotate", type=int, default=0, choices=[0, 90, 180, 270],
                        help="Rotate image counterclockwise (photo supplied in this assignment: 90)")
    parser.add_argument("--threshold", type=int, default=125,
                        help="Grayscale threshold for ink pixels; 125 works for the supplied photo")
    parser.add_argument("--min-area", type=int, default=80, help="Minimum connected-component area in pixels")
    parser.add_argument("--prepare-only", action="store_true", help="Preprocess and save PNGs, without loading model")
    return parser.parse_args()


def open_gray(path):
    # imdecode handles Windows filenames containing non-ASCII characters.
    raw_bytes = np.fromfile(str(path), dtype=np.uint8)
    gray = cv2.imdecode(raw_bytes, cv2.IMREAD_GRAYSCALE)
    if gray is None:
        raise ValueError(f"Could not read image: {path}")
    return gray


def orient(gray, degrees):
    return {
        0: lambda im: im,
        90: lambda im: cv2.rotate(im, cv2.ROTATE_90_COUNTERCLOCKWISE),
        180: lambda im: cv2.rotate(im, cv2.ROTATE_180),
        270: lambda im: cv2.rotate(im, cv2.ROTATE_90_CLOCKWISE),
    }[degrees](gray)


def convert_mnist(single_mask):
    """Preserve aspect ratio, fit inside 20x20, center by pixel mass in 28x28."""
    h, w = single_mask.shape
    scale = 20 / max(w, h)
    new_w, new_h = max(1, round(w * scale)), max(1, round(h * scale))
    resized = cv2.resize(single_mask, (new_w, new_h), interpolation=cv2.INTER_AREA)

    canvas = np.zeros((28, 28), dtype=np.uint8)
    top, left = (28 - new_h) // 2, (28 - new_w) // 2
    canvas[top:top + new_h, left:left + new_w] = resized

    moments = cv2.moments(canvas)
    if moments["m00"] > 0:
        cx = moments["m10"] / moments["m00"]
        cy = moments["m01"] / moments["m00"]
        dx, dy = 13.5 - cx, 13.5 - cy
        matrix = np.float32([[1, 0, dx], [0, 1, dy]])
        canvas = cv2.warpAffine(canvas, matrix, (28, 28), flags=cv2.INTER_LINEAR,
                                borderMode=cv2.BORDER_CONSTANT, borderValue=0)
    return canvas


def prepare_digits(gray, threshold, min_area):
    _, ink = cv2.threshold(gray, threshold, 255, cv2.THRESH_BINARY_INV)
    count, regions, boxes, _ = cv2.connectedComponentsWithStats(ink, connectivity=8)
    # Every handwritten digit in the supplied image is a single connected component.
    # Components much smaller than a digit are background noise.
    detected = []
    for index in range(1, count):
        x, y, w, h, area = map(int, boxes[index])
        if area < min_area or w < 10 or h < 20:
            continue
        crop = ((regions[y:y + h, x:x + w] == index).astype(np.uint8) * 255)
        detected.append((x, y, w, h, convert_mnist(crop)))
    detected.sort(key=lambda component: component[0])
    if not detected:
        raise ValueError("No digits detected. Check --rotate and --threshold.")
    return detected


def render_preview(digits, predicted=None, confidences=None, actual=None):
    tile_size = 84
    gap = 10
    card_w = 104
    card_h = 128 if predicted is None else 148
    out = Image.new("RGB", (len(digits) * card_w, card_h), "#f0f0f0")
    draw = ImageDraw.Draw(out)
    for i, (_, _, _, _, digit) in enumerate(digits):
        tile = Image.fromarray(digit).resize((tile_size, tile_size), Image.Resampling.NEAREST).convert("RGB")
        out.paste(tile, (i * card_w + gap, 6))
        draw.text((i * card_w + gap, 95), f"Digit {i+1}", fill="black")
        if predicted is not None:
            ok = (actual is None or str(predicted[i]) == actual[i])
            color = "#127044" if ok else "#bf2828"
            draw.text((i * card_w + gap, 113), f"Pred {predicted[i]} ({confidences[i]:.0%})", fill=color)
    return out


def main():
    args = parse_args()
    if args.number is not None and not args.number.isdigit():
        raise ValueError("--number must contain digits only (0-9).")
    if not args.image.is_file():
        raise FileNotFoundError(f"Photo not found: {args.image}")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    digits_dir = args.output_dir / "digits"
    digits_dir.mkdir(parents=True, exist_ok=True)

    gray = orient(open_gray(args.image), args.rotate)
    detected = prepare_digits(gray, args.threshold, args.min_area)
    if args.number is not None and len(args.number) != len(detected):
        raise ValueError(
            f"Detected {len(detected)} components but --number has {len(args.number)} digits. "
            "Inspect rotation/threshold; do not report accuracy for incorrect segmentation."
        )

    # Save visual evidence of the actual preprocessing; no data augmentation is performed.
    marked = cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)
    for i, (x, y, w, h, digit) in enumerate(detected, 1):
        cv2.rectangle(marked, (x-5, y-5), (x+w+5, y+h+5), (0, 125, 0), 3)
        cv2.putText(marked, str(i), (x, y-12), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 100, 0), 2)
        Image.fromarray(digit).save(digits_dir / f"digit_{i:02d}.png")
    Image.fromarray(cv2.cvtColor(marked, cv2.COLOR_BGR2RGB)).save(args.output_dir / "segmentation.png")
    render_preview(detected).save(args.output_dir / "mnist_preview.png")
    print(f"Detected: {len(detected)} digits")
    print(f"Prepared images: {digits_dir.resolve()}")
    if args.prepare_only:
        print("Preparation completed. Model was not loaded; no predictions were made.")
        return

    if not args.model.is_file():
        raise FileNotFoundError(
            f"Checkpoint not found: {args.model}. Choose --model path or run --prepare-only."
        )
    import torch
    from model import MLP

    summary_path = args.model.parent / "summary.json"
    if summary_path.is_file():
        hyper = json.loads(summary_path.read_text(encoding="utf-8")).get("hyperparameters", {})
        hidden1, hidden2 = int(hyper.get("hidden1", 256)), int(hyper.get("hidden2", 128))
    else:
        hidden1, hidden2 = 256, 128
        print("No summary.json found; using baseline architecture (256, 128).")

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    net = MLP(hidden1, hidden2).to(device)
    net.load_state_dict(torch.load(args.model, map_location=device, weights_only=True))
    net.eval()

    images = np.stack([digit for (_, _, _, _, digit) in detected]).astype(np.float32) / 255.0
    # Exactly the same MNIST normalization that train.py used.
    inputs = torch.from_numpy((images - 0.1307) / 0.3081).unsqueeze(1).to(device)
    with torch.inference_mode():
        probabilities = torch.softmax(net(inputs), dim=1).cpu().numpy()
    predicted = probabilities.argmax(axis=1).tolist()
    confidences = probabilities.max(axis=1).tolist()
    print(f"Actual:    {args.number if args.number else '(not provided)'}")
    print("Predicted:", "".join(map(str, predicted)))
    rows = []
    for i, (pred, confidence) in enumerate(zip(predicted, confidences), 1):
        actual_digit = args.number[i - 1] if args.number else ""
        correct = (str(pred) == actual_digit) if args.number else None
        rows.append({"index": i, "actual": actual_digit, "predicted": pred,
                     "confidence": round(float(confidence), 6), "correct": correct})
        status = "correct" if correct else "wrong" if correct is False else "unlabeled"
        print(f"Digit {i:02d} | real={actual_digit or '-'} | predicted={pred} | confidence={confidence:.1%} | {status}")
    accuracy = None
    if args.number:
        accuracy = sum(row["correct"] for row in rows) / len(rows) * 100
        print(f"Handwriting accuracy: {accuracy:.2f}% ({sum(row['correct'] for row in rows)}/{len(rows)})")
    print("Note: softmax confidence is not guaranteed to be a calibrated probability.")

    with (args.output_dir / "predictions.csv").open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    (args.output_dir / "predictions.json").write_text(
        json.dumps({"actual": args.number, "predicted": "".join(map(str, predicted)),
                    "accuracy_percent": accuracy, "checkpoint": str(args.model),
                    "rotation_degrees_ccw": args.rotate, "threshold": args.threshold,
                    "digits": rows}, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    render_preview(detected, predicted, confidences, args.number).save(args.output_dir / "prediction_preview.png")
    print(f"Saved all results to: {args.output_dir.resolve()}")


if __name__ == "__main__":
    main()
